//! stub.rs — стаб первого уровня (IRAM 0x2FFE4000, файл 0x054..0x3BF).
//!
//! РЕКОНСТРУКЦИЯ ОРИГИНАЛА (rebuild/stub.s, disasm_stub.asm, docs/01 §2):
//! стаб — инициализатор DDR-контроллера (база 0x90020000) и системного блока
//! (0x90000000). Bootrom вызывает 0x2FFE4000 (поле заголовка +0x2C), стаб
//! поднимает память и ВОЗВРАЩАЕТ УПРАВЛЕНИЕ (`pop {r0-r5}; mov pc, lr`
//! @0x2FFE432C). Цикла копирования тела в стабе нет — перенос тела в SDRAM
//! выполняет вызывающая сторона (bootrom/хост по USBL-протоколу), затем
//! управление получает sysInit тела @0x30004000.
//!
//! Код стаба обязан жить в IRAM целиком (SDRAM ещё не инициализирована),
//! поэтому это `global_asm!` — штатный механизм Rust для стартового кода.
//! Раскладка байт-в-байт как в оригинале:
//!   0x2FFE4000  вход: push {r0-r5}; b ddr_init
//!   0x2FFE4008..0x2FFE410F  нулевая зона оригинала (63 слова)
//!   0x2FFE4110..0x2FFE4143  маркерные слова оригинала («Copyright (c) 2012
//!                            Huawei...», «ALLD09. ман.NTDL») — данные,
//!                            назначение не установлено (docs/01 §7-5)
//!   0x2FFE4144..  процедура DDR-инициализации (та же последовательность
//!                 регистровых записей и литералов, docs/01 §8.1)
//!
//! Регистровая последовательность (Rust-эквивалент см. `ddr_init_reference`):
//! 1. [0x90000038] &= ~0x20000                          (системный блок)
//! 2. [DDR+0x810] = 0x1D; 2 прохода PHY: 0x1006, потом 0x1003
//!    в 12 регистров +0x430,+0x434,+0x440..+0x464 (0x438/0x43C пропущены)
//! 3. [DDR+0x58] = 0x7771E000; [DDR+4] = 0
//! 4. поллинг бита 31 [DDR+0x808]; [DDR+0x804]=0x6B; [DDR+0x800]=0x40000000;
//!    повторный поллинг бита 31; холостая задержка 0x4E20
//! 5. [DDR+0x14]=0x32; [0x18]=0; [0x1C]=0x21E00110; [0x20]=0x30005300;
//!    [0x2C]=[0x30]=[0x34]=[0x38]=0x22; [0x40]=0x30000000
//! 6. [0x50]=0x23440C08; [0x54]=0x0E321318; [0x58]=0x22300049;
//!    [0x5C]=0xFFC00022; [0xAC]=0x0F000103
//! 7. [DDR+8]=1; поллинг бита 3 [DDR+0] (цикл, пока бит установлен);
//!    [DDR+0x20]=0x30005700; [DDR+0xF8]=1
//! 8. [0x90000470]=0x30000000; [0x90000474]=0x3FF00000; [0x90000400]|=1
//! 9. pop {r0-r5}; возврат в bootrom

/// База DDR-контроллера (литерал 0x2FFE4334).
pub const DDR_BASE: usize = 0x9002_0000;
/// База системного блока CRG/PWRCTRL.
pub const SYSCRTL_BASE: usize = 0x9000_0000;

core::arch::global_asm! {
    ".section .stub.entry, \"ax\"",
    ".align 2",
    ".global stub_entry",
    ".type stub_entry, %function",

    // ================= вход стаба @ 0x2FFE4000 =================
    "stub_entry:",
    "    push {{r0, r1, r2, r3, r4, r5}}",     // как оригинал @0x2FFE4000
    "    b ddr_init",                          // как b 0x2FFE4144 @0x2FFE4004

    // ---- нулевая зона оригинала 0x2FFE4008..0x2FFE4110 (66 слов) ----
    ".rept 66",
    "    .word 0",
    ".endr",

    // ---- маркерные слова оригинала @0x2FFE4110..0x2FFE4144 (байт-в-байт,
    //      «Copyright 2008-2020 HUAWEI TECHNOLOGIES CO., LTD.») ----
    ".word 0x79706F43",   // 0x2FFE4110 «Copy"
    ".word 0x68676972",   // 0x2FFE4114 «righ"
    ".word 0x30322074",   // 0x2FFE4118 «t 20"
    ".word 0x322D3830",   // 0x2FFE411C «08-2"
    ".word 0x20303230",   // 0x2FFE4120 "020 "
    ".word 0x57415548",   // 0x2FFE4124 «HUAWEI TECHNO»
    ".word 0x54204945",
    ".word 0x4E484345",
    ".word 0x474F4C4F",
    ".word 0x20534549",
    ".word 0x2C2E4F43",   // 0x2FFE4138 "CO., "
    ".word 0x44544C20",   // 0x2FFE413C " LTD."
    ".word 0x0000002E",   // 0x2FFE4140

    // ================= процедура DDR @ 0x2FFE4144 =================
    "ddr_init:",
    // r1 = 0x90000000 (системный блок); [r1+0x38] &= ~0x20000
    "    ldr r1, =0x90000000",
    "    ldr r2, [r1, #0x38]",
    "    bic r2, r2, #0x20000",
    "    str r2, [r1, #0x38]",

    // r1 = 0x90020000 (DDR); [r1+0x810] = 0x1D
    "    ldr r1, =0x90020000",
    "    mov r2, #0x1D",
    "    str r2, [r1, #0x810]",

    // проход 1: 0x00001006 в 12 регистров PHY (0x2FFE4164..0x2FFE41C0)
    "    ldr r2, =0x00001006",
    "    str r2, [r1, #0x430]",
    "    str r2, [r1, #0x434]",
    "    str r2, [r1, #0x440]",
    "    str r2, [r1, #0x444]",
    "    str r2, [r1, #0x448]",
    "    str r2, [r1, #0x44C]",
    "    str r2, [r1, #0x450]",
    "    str r2, [r1, #0x454]",
    "    str r2, [r1, #0x458]",
    "    str r2, [r1, #0x45C]",
    "    str r2, [r1, #0x460]",
    "    str r2, [r1, #0x464]",

    // проход 2: 0x00001003 в те же 12 регистров (0x2FFE41C4..0x2FFE4220)
    "    ldr r2, =0x00001003",
    "    str r2, [r1, #0x430]",
    "    str r2, [r1, #0x434]",
    "    str r2, [r1, #0x440]",
    "    str r2, [r1, #0x444]",
    "    str r2, [r1, #0x448]",
    "    str r2, [r1, #0x44C]",
    "    str r2, [r1, #0x450]",
    "    str r2, [r1, #0x454]",
    "    str r2, [r1, #0x458]",
    "    str r2, [r1, #0x45C]",
    "    str r2, [r1, #0x460]",
    "    str r2, [r1, #0x464]",

    // [DDR+0x58] = 0x7771E000 (литерал 0x2FFE4340); [DDR+4] = 0
    "    ldr r2, =0x7771E000",
    "    str r2, [r1, #0x58]",
    "    mov r2, #0",
    "    str r2, [r1, #4]",

    // поллинг: ждать бит 31 в [DDR+0x808] (0x2FFE4234)
    "1:  ldr r2, [r1, #0x808]",
    "    tst r2, #0x80000000",
    "    beq 1b",

    // [DDR+0x804] = 0x6B; [DDR+0x800] = 0x40000000 (0x2FFE4244)
    "    mov r2, #0x6B",
    "    str r2, [r1, #0x804]",
    "    ldr r2, =0x40000000",
    "    str r2, [r1, #0x800]",

    // повторный поллинг бита 31 (0x2FFE4254)
    "2:  ldr r2, [r1, #0x808]",
    "    tst r2, #0x80000000",
    "    beq 2b",

    // холостая задержка 0x4E20 итераций (0x2FFE4264, литерал 0x2FFE4344)
    "    ldr r3, =0x4E20",
    "3:  subs r3, r3, #1",
    "    bne 3b",

    // серия конфигурационных записей (0x2FFE4274..0x2FFE42B8)
    "    mov r2, #0x32",
    "    str r2, [r1, #0x14]",
    "    mov r2, #0",
    "    str r2, [r1, #0x18]",
    "    ldr r2, =0x21E00110",              // литерал 0x2FFE4348
    "    str r2, [r1, #0x1C]",
    "    ldr r2, =0x30005300",              // литерал 0x2FFE434C
    "    str r2, [r1, #0x20]",
    "    mov r2, #0x22",
    "    str r2, [r1, #0x2C]",
    "    str r2, [r1, #0x30]",
    "    str r2, [r1, #0x34]",
    "    str r2, [r1, #0x38]",
    "    ldr r2, =0x30000000",              // база SDRAM
    "    str r2, [r1, #0x40]",

    // тайминги PHY (0x2FFE42BC..0x2FFE42E0)
    "    ldr r2, =0x23440C08",              // литерал 0x2FFE4350
    "    str r2, [r1, #0x50]",
    "    ldr r2, =0x0E321318",              // литерал 0x2FFE4354
    "    str r2, [r1, #0x54]",
    "    ldr r2, =0x22300049",              // литерал 0x2FFE4358
    "    str r2, [r1, #0x58]",
    "    ldr r2, =0xFFC00022",              // литерал 0x2FFE435C
    "    str r2, [r1, #0x5C]",
    "    ldr r2, =0x0F000103",              // литерал 0x2FFE4360
    "    str r2, [r1, #0xAC]",

    // [DDR+8] = 1 — старт контроллера (0x2FFE42E4)
    "    mov r2, #1",
    "    str r2, [r1, #8]",

    // поллинг бита 3 в [DDR+0]: цикл, пока бит установлен (0x2FFE42EC)
    "4:  ldr r2, [r1]",
    "    tst r2, #8",
    "    bne 4b",

    // [DDR+0x20] = 0x30005700 (перезапись); [DDR+0xF8] = 1 (0x2FFE42FC)
    "    ldr r2, =0x30005700",              // литерал 0x2FFE4364
    "    str r2, [r1, #0x20]",
    "    mov r2, #1",
    "    str r2, [r1, #0xF8]",

    // системный блок: окно SDRAM (0x2FFE430C..0x2FFE4328)
    "    ldr r1, =0x90000000",
    "    ldr r2, =0x30000000",
    "    str r2, [r1, #0x470]",
    "    ldr r2, =0x3FF00000",              // литерал 0x2FFE4368 (маска ~1 ГБ)
    "    str r2, [r1, #0x474]",
    "    ldr r2, [r1, #0x400]",
    "    orr r2, r2, #1",
    "    str r2, [r1, #0x400]",

    // возврат в bootrom (как pop {r0-r5}; mov pc, lr @0x2FFE432C)
    "    pop {{r0, r1, r2, r3, r4, r5}}",
    "    mov pc, lr",

    ".size stub_entry, . - stub_entry",
    ".section .text",
}

/// Rust-справочник регистровой последовательности стаба — выполняется из
/// тела (sysInit оригинала тоже повторяет запись окна SDRAM в системном
/// блоке: boot_01.c, sysInit → `*(DAT_30004164+0x470)=0x30000000` и т.д.).
///
/// # Safety
/// Только голое железо, до любого использования SDRAM-контента.
#[allow(dead_code)]
pub unsafe fn sys_window_setup() {
    use crate::mmio::*;
    write32(SYSCRTL_BASE + 0x470, 0x3000_0000);
    write32(SYSCRTL_BASE + 0x474, 0x3FF0_0000);
    rmw32(SYSCRTL_BASE + 0x400, 0, 1);
}
